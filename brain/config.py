# Размер мозга = общее число нейронов всех зон.
# Число синапсов растёт линейно (fixed in-degree), ~190 на нейрон.
# Человек: ~86 млрд нейронов, ~1e14 синапсов — в 6 ГБ GPU
# не помещается ни при каком кодировании.
# [замер] RTX 4050 6 ГБ: small 0.3 ГБ, medium 1.4 ГБ, large ~7 ГБ
# (не влезает, WSL уходит в системную память и падает до 7 ток/с).
PRESETS = {
    "tiny": 2_000,
    "small": 20_000,
    "medium": 100_000,
    "large": 500_000,
    "xlarge": 1_000_000,
}


@dataclass
class AreaSpec:
    """
    Зона мозга.

    kind = "cortex"  E (AdEx) + I (быстрый LIF), быстрые синапсы
    kind = "memory"  E с медленным NMDA-подобным током (рабочая память)
    share           доля от общего числа нейронов
    """

    name: str
    title: str
    share: float
    kind: str = "cortex"
    # Локальные связи внутри зоны. [не подбиралось] 50 входов.
    k_ee: int = 50
    ee_plastic: bool = True
    # [биология] врождённые связи слабые и случайные: сильные
    # должны появиться только от опыта.
    ee_weight: tuple[float, float] = (0.05, 0.20)
    ee_cap: float = 3.0
    # Целевая доля E-нейронов, отвечающих на слово.
    # [биология] в коре на стимул отвечают единицы процентов клеток.
    target_activity: float = 0.04


@dataclass
class PathwaySpec:
    """
    Проводящий путь между зонами: E-нейроны src -> E и I нейроны dst.

    plastic=True — путь учится (STDP + dopamine).
    plastic=False — врождённая «проводка».
    """

    src: str
    dst: str
    k: int
    weight: tuple[float, float]
    plastic: bool = False
    cap: float = 2.0
    # Сколько входов от src получает каждый I-нейрон dst
    # (feedforward inhibition: сильный вход сразу будит торможение).
    # [замер] без него зоны срывались в синхронные залпы.
    k_inhibitory: int = 50
    inhibitory_weight: float = 1.5


def default_areas() -> list[AreaSpec]:
    # Доли зон [не подбиралось]: смысловой памяти — больше всех.
    return [
        AreaSpec(
            "auditory", "слуховая кора / зона Вернике (формы слов)",
            0.20, k_ee=30, ee_plastic=False, target_activity=0.05,
        ),
        AreaSpec(
            # [не подбиралось] 100 входов E->E: основная память, ей нужно
            # больше всего синапсов.
            "association", "ассоциативная кора (смысловая память)",
            0.50, k_ee=100,
        ),
        AreaSpec(
            # Рабочая память держит больше активных клеток (8%): в ней
            # одновременно звучат несколько последних слов.
            "prefrontal", "префронтальная кора (рабочая память)",
            0.20, kind="memory", k_ee=20, ee_plastic=False,
            ee_weight=(0.05, 0.05), target_activity=0.08,
        ),
        AreaSpec(
            "motor", "моторная речевая зона / зона Брока (рот)",
            0.10, k_ee=30, ee_plastic=False,
        ),
    ]


def default_pathways() -> list[PathwaySpec]:
    return [
        # Восприятие: формы слов -> смысл.
        # [замер] k=100 и вес 4: одно и то же слово даёт ансамбль со
        # сходством 0.58 между повторами против 0.05 у разных слов.
        # k=20 давало 0.07 (смысловая зона отвечала шумом); вес 5-8
        # не лучше, а моторная зона начинала отвечать на всё подряд.
        PathwaySpec("auditory", "association", k=100, weight=(4.0, 4.0)),
        # Смысл -> рабочая память (эхо последних слов).
        # [замер] вес 3 — память молчала на коротких фразах; 10 —
        # 12% активных и шум в ожиданиях; 6 — память различает
        # «открыть файл» / «закрыть файл» (0.43 повтор против 0.32).
        # Торможение 6 = вес возбуждения: иначе синхронные залпы.
        PathwaySpec("association", "prefrontal", k=100, weight=(6.0, 6.0),
                    inhibitory_weight=6.0),
        # Контекст -> ожидание следующего смысла. Учится.
        # [замер] k=20: при k=50-60 ожидания сильнее зашумлены.
        # Сейчас его вклад в ожидание выключен (context_gain=0).
        PathwaySpec("prefrontal", "association", k=20, weight=(0.02, 0.10),
                    plastic=True, cap=2.0, k_inhibitory=0),
        # Смысл -> артикуляция (рот).
        # [замер] вес 6: моторный ансамбль слова 0.33-0.45 сходства между
        # повторами (4 -> 0.26). k=300 хуже: 44-83 из 224 слов «рот»
        # узнаёт против 130 из 258 при k=100.
        PathwaySpec("association", "motor", k=100, weight=(6.0, 6.0),
                    inhibitory_weight=6.0),
    ]


@dataclass
class BrainConfig:
    # ------------------------------------------------------------------
    # Железо
    # ------------------------------------------------------------------
    device: str = os.environ.get("BRAIN_DEVICE", "auto")  # auto | cuda | cpu
    seed: int = 42
    # [не подбиралось] 1 мс: стандарт для LIF/AdEx с Эйлером.
    dt_ms: float = 1.0
    # Верхняя граница доли нейронов, стреляющих за один шаг
    # (размер event-таблицы). Лишние спайки теряются и считаются в /stats.
    # [замер] 1% — терялись сотни тысяч спайков за проход (залпы рабочей
    # памяти до 30% зоны за 1 мс, ещё до τsyn 5 мс). После устранения
    # залпов, при чтении на 100k: медиана 0.03%, 99.9% шагов < 1.02%,
    # максимум 1.54%. 2% — с запасом; 5% тормозило большие мозги
    # (200k: 7 ток/с — шаг тратит время на пустые строки таблицы).
    max_spike_fraction: float = 0.02
    # [замер] пик за шаг: 2k нейронов — 16.9%, 20k — 7.9%, 100k — 1.5%.
    # Поэтому не меньше 2000 строк (но не больше 20% мозга): tiny —
    # 400 (20%), small — 2000 (10%), 100k+ — 2%.
    min_spike_table: int = 2000
    # Отвергнутые варианты [замер]: таблицы разного размера под пик
    # прошлых 10 мс — теряли сотни тысяч спайков на начале слов;
    # точный список спайков без CUDA Graph — медленнее
    # (300k: 6 ток/с против 9, 100k: 10 против 25).

    # ------------------------------------------------------------------
    # Размер и анатомия.
    # ------------------------------------------------------------------
    size: str = os.environ.get("BRAIN_SIZE", "small")
    # [биология] ~20% тормозных нейронов в неокортексе.
    inhibitory_fraction: float = 0.20
    areas: list[AreaSpec] = field(default_factory=default_areas)
    pathways: list[PathwaySpec] = field(default_factory=default_pathways)

    # Локальные связи с торможением внутри каждой зоны.
    # [замер] ei=1, ie=-2: синхронные залпы до 100% зоны;
    # ei=3, ie=-6..-8: зоны молчали. 2 / -4 — рабочая точка, дальше
    # возбудимость доводит гомеостаз.
    k_ei: int = 50
    k_ie: int = 50
    k_ii: int = 25
    ei_weight: float = 2.0
    ie_weight: float = -4.0
    ii_weight: float = -1.5

    # ------------------------------------------------------------------
    # Нейроны (мВ, мс). Cortex E — AdEx, I — быстрый LIF,
    # memory E — LIF с медленным NMDA-подобным током.
    # ------------------------------------------------------------------
    # [биология] τm, порог, покой, сброс — типичные для пирамидных клеток.
    e_tau_m: float = 20.0
    # [замер] AMPA/GABA 2 мс -> синхронные залпы (до 929 из 3200 нейронов
    # рабочей памяти за 1 мс); 5 мс [биология] — залпов нет.
    e_tau_syn: float = 5.0
    e_delta_t: float = 2.0
    # [биология] спайковая адаптация пирамидных клеток.
    e_adapt_tau: float = 150.0
    e_adapt_b: float = 1.0
    i_tau_m: float = 10.0
    # Быстрые интернейроны (PV) ближе к порогу, чем пирамидные клетки:
    # торможение должно успевать раньше залпа E.
    # [замер] без этого ассоциативная зона копила вход ~25 мс и давала
    # залп (158 из 8000 за 1 мс), торможение приходило уже после.
    i_excitability: float = 8.0
    i_tau_syn: float = 5.0
    # [биология] NMDA ~100-400 мс. При 70 мс на слово 400 мс — след
    # нескольких последних слов.
    memory_tau_syn: float = 400.0
    # Медленный ток рабочей памяти относительно быстрого.
    # [замер] 1.0 — память не успевала зарядиться за 2 слова пробы;
    # 0.5 — заряжается. Вариант «почти без быстрого тока» (AMPA 0.1,
    # NMDA 1.5, чтобы память держала прошлое, а не текущее слово)
    # дал +0.02 MRR на неоднозначных переходах — в пределах шума.
    memory_nmda_ratio: float = 0.5
    memory_ampa_ratio: float = 1.0
    memory_tau_m: float = 20.0
    v_rest: float = -70.0
    v_threshold: float = -50.0
    v_reset: float = -58.0
    refractory_ms: float = 2.0

    # Гомеостаз возбудимости (intrinsic plasticity): после каждого слова
    # возбудимость зоны (ток покоя, мВ) сдвигается к target_activity.
    # [замер] ручная подгонка весов без него стояла «на лезвии» —
    # зона либо молчала, либо взрывалась. С ним — 4-5% в каждой зоне.
    # Скорость 0.5 мВ и пределы [не подбиралось].
    homeostasis_rate: float = 0.5
    homeostasis_bias_range: tuple[float, float] = (-10.0, 18.0)
    # «Пренатальная» калибровка: столько случайных звуков мозг
    # слышит при рождении. [замер] 400 и 1000 дают одинаковую
    # рабочую точку; 400 — 3.5 с.
    calibration_tokens: int = 400

    # Фоновый шум: Poisson-вход на каждый нейрон.
    background_rate_hz: float = 1000.0
    # [замер] 0.5 — ансамбль слова в смысловой зоне почти случаен
    # (сходство повторов 0.07); 0.2 — 0.43; 0.1 — 0.57.
    background_weight: float = 0.1
    # [не подбиралось] рабочей памяти шум нужнее: её нейроны висят
    # у порога на тоническом NMDA-токе. Залпы он не убрал (их убрали
    # τsyn 5 мс + торможение), но и не мешает.
    memory_background_weight: float = 0.3

    # ------------------------------------------------------------------
    # Пластичность: STDP -> eligibility trace -> dopamine.
    # Вес меняется только когда приходит dopamine.
    # ------------------------------------------------------------------
    # Ядро LTP со сдвигом: exp(-t/80) - exp(-t/30), пик через ~45 мс.
    # Одновременные спайки (одно слово) почти не усиливаются, спайк
    # ~одно слово назад — сильнее всего (time-lagged Hebbian, медленная
    # кинетика NMDA).
    # [замер] главное улучшение памяти: место правильного слова из
    # идеального ансамбля [113, 54, 61, 2, 198 …] -> [10, 1, 18, 3, 6 …]
    # из 270; угадывание при чтении 10% -> 24%.
    stdp_tau_plus: float = 80.0
    stdp_ltp_rise: float = 30.0
    # [замер] окно сбалансировано с перевесом депрессии
    # (Song/Miller/Abbott 2000). При A- = 0.004, τ- = 20 (перекос в
    # LTP в 5 раз) треть синапсов росла без причины.
    stdp_tau_minus: float = 40.0
    stdp_a_plus: float = 0.010
    stdp_a_minus: float = 0.012
    # Сколько живёт след для дофамина.
    # [замер] 1500 мс (~20 слов): мозг учил «какие слова рядом в тексте»,
    # а не «что идёт следом». 200 мс (~3 слова) — закрепляется
    # именно последний переход. 100 мс не лучше.
    eligibility_tau: float = 200.0
    # [замер] 3.0 — хуже, 0.3-0.5 — без явного выигрыша.
    dopamine_learning_rate: float = 1.0

    # Выученное = рост веса относительно веса при рождении.
    # [замер] на трёх зёрнах разница в шуме (MRR 0.42 против 0.45);
    # оставлено как более честное определение.
    learned_from_birth: bool = True
    # Вклад рабочей памяти в ожидание.
    # [замер] три зерна, MRR фактов / контекста:
    #   без вклада          0.564 / 0.303
    #   gain 0.5            0.506 / 0.265
    #   gain 1.0            0.424 / 0.211
    #   gain 4 / 10         ещё хуже
    # На самом чтении одна память предсказывает в 8 раз лучше
    # случайного (MRR 0.18), но в сумме с текущим словом ничего не
    # добавляет. Пока выключено; путь продолжает учиться.
    context_gain: float = 0.0
    # Как контекст входит в ожидание: "add" | "gain" (умножает отклик
    # на текущее слово). [замер] "gain" +0.01 — в шуме.
    context_mode: str = "add"
    # Правило обучения путей ИЗ рабочей памяти:
    #   "stdp"       — как у коры (порядок спайков);
    #   "covariance" — (активность пре − средняя по зоне) × спайк поста.
    # [замер] covariance не лучше stdp (MRR памяти 0.164 против 0.18).
    context_rule: str = "stdp"
    context_hebb_gain: float = 1.0

    # Homeostatic synaptic scaling (Turrigiano): суммарный входной
    # пластичный вес нейрона не больше budget * врождённая сумма.
    # [не подбиралось] 1.5.
    synaptic_scaling_enabled: bool = True
    synaptic_scaling_budget: float = 1.5
    # [замер] на каждой фразе масштабирование съедало 25% времени
    # чтения на 300k нейронов (обход 57 млн синапсов). Биологически
    # это медленный процесс (часы) — раз в 20 фраз достаточно.
    synaptic_scaling_every: int = 20

    # Структурная пластичность: синапс, ослабший ниже
    # prune_fraction × минимальный врождённый вес пути, отмирает,
    # вместо него растёт новый. Проверка раз в N фраз.
    # [замер] абсолютный порог 0.02 совпадал с минимальным весом пути
    # «память -> смысл»: 2 млн синапсов за 3 прохода гибли и росли
    # заново. Относительный порог 0.25 — отмирают только ослабленные опытом.
    structural_plasticity_enabled: bool = True
    prune_fraction: float = 0.25
    rewire_every_sentences: int = 50

    # ------------------------------------------------------------------
    # Dopamine от prediction error.
    #   предсказание сбылось          -> 0
    #   ошибка ниже порога            -> 0 (мелкая неожиданность)
    #   ошибка выше порога            -> растёт квадратично
    # Поэтому выученное перестаёт перестраивать сеть.
    # [замер] за 8 проходов dopamine падает 66 -> 24-33 при росте
    # угадывания 9 -> 15-17 из 22. Порог и усиление [не подбиралось].
    # ------------------------------------------------------------------
    surprise_threshold: float = 0.3
    surprise_dopamine_gain: float = 6.0
    # Врождённые сигналы из диалога: поощрение и наказание.
    praise_words: tuple[str, ...] = ("+", "да", "верно", "правильно", "молодец", "отлично")
    blame_words: tuple[str, ...] = ("-", "нет", "неверно", "неправильно", "ошибка")
    # [не подбиралось] равен максимальному surprise-дофамину.
    feedback_dopamine: float = 6.0

    # ------------------------------------------------------------------
    # Ухо: текст -> sensory-каналы -> слуховая кора.
    # ------------------------------------------------------------------
    # [не подбиралось] 32 канала из 2048 на слово: случайные коды
    # разных слов почти не пересекаются.
    sensory_size: int = 2048
    sensory_channels_per_token: int = 32
    sensory_rate_hz: float = 150.0
    k_sensory: int = 20
    # [замер] нейрону нужно ~2 совпавших канала, чтобы ответить:
    # слуховая зона даёт сходство повторов 0.90 против 0.05.
    sensory_weight: float = 3.0
    sensory_inhibitory_gain: float = 1.0

    # ------------------------------------------------------------------
    # Язык.
    # ------------------------------------------------------------------
    # [не подбиралось] 60 мс на слово + 10 мс паузы: короткая пауза,
    # чтобы конец слова A и начало B попадали в окно STDP.
    stimulus_ms: float = 60.0
    gap_ms: float = 10.0
    rest_ms: float = 150.0
    # Пауза перед диагностической пробой: рабочая память
    # затухает (~2.5 τ), проба видит только свои слова.
    probe_pause_ms: float = 1000.0
    readout_rate: float = 0.3
    readout_top_k: int = 64
    # Ожидание -> только самые возбуждённые нейроны (k-WTA).
    # [замер] с отбором 4% хуже: факты top-5 0/8 против 5/8 без отбора.
    expectation_top_fraction: float = 0.0
    # «Рот»: разреживать ли ожидание перед моторной зоной.
    # [замер] без разреживания рот узнаёт 130 из 258 слов, с ним 119.
    mouth_sparse: bool = False
    # Ответ: первые слова самые обоснованные, дальше мысль уплывает.
    # [замер] оценки всех слов 0.07–0.20 — абсолютный порог их не
    # различает, поэтому он низкий, а решает относительный.
    generate_max_tokens: int = 8
    generate_min_score: float = 0.05
    # Остановка, если лидер выделяется среди 20 лучших меньше, чем
    # в 1.2 раза. [замер] без порога верны 39% слов, с 1.2 — 44%,
    # с 1.5 — 52%, но ответы почти пустые.
    generate_min_margin: float = 1.2
    # Молчать («не знаю»), если по собственному опыту мозга слово
    # окажется верным реже чем в 15% случаев. Работает, когда мозг
    # проверил себя хотя бы 200 раз (до этого — только margin).
    # [замер] на train-data самые вялые ожидания сбываются в 10–13%,
    # средние — в 18–20%. Порог 0.2 лежал ровно на границе: от прогона
    # к прогону мозг то отвечал «берлин», то «не знаю» на всё.
    generate_min_confidence: float = 0.15
    confidence_min_experience: int = 200

    # Незнакомые слова: мозг спрашивает «а что такое X?» (врождённый
    # рефлекс любопытства); ответ человека учит его как обычная реплика.
    ask_about_unknown: bool = True
    # [не подбиралось] спрашивать только про слова от 4 букв (служебные
    # «и», «это», «на» короче) и не больше двух за раз.
    ask_min_letters: int = 4
    # Слово знакомо, если мозг слышал его хотя бы столько раз.
    familiar_after: int = 1

    # Гиппокамп и сон (brain/hippocampus.py).
    # [не подбиралось] сколько фраз помнит гиппокамп.
    hippocampus_capacity: int = 50_000
    # Предпочтение неожиданного при проигрывании: 0 — поровну, 1 —
    # пропорционально дофамину фразы.
    # [замер] train-data, 2 зерна, равные вычисления (факты / контекст /
    # угадывание): 3 прохода 0.438 / 0.149 / 0.345; 1 проход + сон
    # с приоритетом 0.253 / 0.298 / 0.360; 1 проход + сон поровну
    # 0.488 / 0.424 / 0.362. Приоритет застревает на трудных фразах.
    replay_priority: float = 0.0
    # Засыпать, когда с мозгом не говорят столько секунд и есть
    # невыученные впечатления. [не подбиралось]
    sleep_when_idle: bool = True
    idle_sleep_seconds: float = 30.0
    # Фраз за одну порцию сна: между порциями мозг проверяет, не
    # пришло ли сообщение (чтобы проснуться за ~1-2 секунды).
    sleep_batch: int = 10
    # Сколько раз проиграть каждое новое впечатление за сон.
    # [замер] 1 проход 150 фраз + сон (факты / контекст / угадывание):
    # 300 проигрываний (2 на фразу) 0.488 / 0.424 / 0.362; 1500 (5) —
    # 0.629 / 0.502 / 0.387; 3000 (10) — 0.592 / 0.292 / 0.360:
    # переучивание — одни фразы вытесняют остальные.
    replays_per_episode: int = 5
    # «Давление сна»: с этого числа новых фраз мозг хочет спать.
    sleepy_after_episodes: int = 50
    # Фраза, давшая во сне меньше дофамина, считается выученной корой
    # и забывается гиппокампом.
    consolidated_salience: float = 1.0

    # Размышление (think): внутренняя речь + проверяющий.
    # [замер] на 14 вопросах train-data (1 проход + сон 300): первое
    # слово верно 5/14 без размышления, 6/14 с проверяющим — правильного
    # слова часто нет среди 20 кандидатов, проверять нечего.
    # [замер] на живом мозге проверяющий принял «компьютеру» на «какая
    # столица россии?»: связь «россии -> компьютеру» в памяти оказалась
    # сильнейшей. Проверка не умнее памяти — пока выключено (/think on).
    thinking_enabled: bool = False
    think_max_steps: int = 20
    # Сколько кандидатов проверять, прежде чем сдаться на этом шаге.
    think_breadth: int = 5
    # Мысль принята, если связь с целью ≥ порога (0.05 ≈ мысль в первых
    # 20 ожиданиях от слова цели или наоборот). [не подбиралось]
    think_accept: float = 0.05

    # Фоновое чтение в вебе: столько фраз за порцию, между порциями
    # мозг отвечает на сообщения. [не подбиралось] ~0.5–1 с на порцию.
    read_portion_sentences: int = 5

    # Живой режим (веб): мозг всё время что-то делает — в тишине
    # размышляет («блуждание мыслей»), иногда заговаривает сам (повод
    # выбирает эмоция) и ждёт ответа. Обычный режим только отвечает.
    live_mode: bool = False
    # Блуждание мыслей: раз в столько секунд тишины. [не подбиралось]
    wander_every_seconds: float = 8.0

    # Инициатива (часть живого режима). [не подбиралось]
    initiative_enabled: bool = True
    initiative_idle_seconds: float = 45.0
    initiative_cooldown_seconds: float = 120.0
    # Делиться выученным, только если уверен хотя бы настолько.
    initiative_share_confidence: float = 0.3

    # Журнал переписки для /reread (последние реплики).
    dialog_log_turns: int = 2000

    # Эмоции (brain/limbic.py): складываются из дофамина, похвалы и
    # уверенности. На обучение не влияют — только отражают состояние;
    # выключено = не обновляются и не показываются.
    emotions_enabled: bool = True

    # Сохранение мозга между запусками.
    save_path: str = os.environ.get("BRAIN_SAVE", "data/brain.pt")
    autosave: bool = True
    # При чтении папок — не чаще раза в N минут: мозг на 300k
    # нейронов весит больше 1 ГБ, а файлов бывает сотня.
    autosave_minutes: float = 10.0

    # Нейрогенез и смерть нейронов (этап 13 roadmap) пока не
    # реализованы: сначала стабильная память и контекст.

    @property
    def total_neurons(self) -> int:
        return PRESETS.get(self.size) or int(self.size)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "BrainConfig":
        data = dict(data)
        data["areas"] = [AreaSpec(**a) for a in data.get("areas", [])] or default_areas()
        data["pathways"] = [PathwaySpec(**p) for p in data.get("pathways", [])] or default_pathways()

        for key in ("praise_words", "blame_words", "homeostasis_bias_range"):
            if key in data:
                data[key] = tuple(data[key])

        known = cls.__dataclass_fields__
        return cls(**{k: v for k, v in data.items() if k in known})
