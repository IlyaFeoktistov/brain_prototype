        # Числа — со стенда, каждое по правилу (DESIGN «Цель в ПФК»):
        #  - column_weight 40: одно услышанное слово (60 мс) зажигает
        #    колонку (6 — гасла, 80 — то же, но 166 Гц);
        #  - ampa_ratio 0.05: держит медленный ток, а не быстрый (при
