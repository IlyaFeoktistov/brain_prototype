@dataclass
class BrainConfig:
    # ------------------------------------------------------------------
    # Железо
    # ------------------------------------------------------------------
    device: str = os.environ.get("BRAIN_DEVICE", "auto")  # auto | cuda | cpu
    # Собрать шаг симуляции torch.compile (слить мелкие ядра). Первый
    # запуск дольше (компиляция). [замер — см. DESIGN «Скорость шага»]
    compile_step: bool = os.environ.get("BRAIN_COMPILE", "1") == "1"
    # Процедурная проводка (brain/wiring.py): врождённые пути с постоянным
    # весом (~41% синапсов) не хранятся — получатели вычисляются хешем в
    # шаге. Задаётся при создании мозга. Размен памяти на скорость:
    # [замер] 20 тыс. нейронов — память −30% (60 → 42 МБ), чтение −23%
    # (65.8 → 50.4 ток/с), факты 24 → 27 (шум). Включать для больших
    # мозгов, когда упираются в видеопамять.
    procedural_wiring: bool = False
    # Задержка в аксоне между зонами (ARCHITECTURE «Строительный блок»):
    # спайк приходит через axon_delay_ms ±50% у каждого синапса, внутри зоны —
    # через шаг, как раньше. Между зонами коры 5–20 мс и больше (Swadlow;
    # Caminiti et al. 2013) — середина 6 мс [не подбиралось]. Врождённые
    # пути с постоянным весом (procedural_wiring) — без задержки (долг).
    axon_delays: bool = False
    axon_delay_ms: float = 6.0
    seed: int = 42
    # [не подбиралось] 1 мс: стандарт для LIF/AdEx с Эйлером.
    # [замер] 20 тыс., 2 прохода train-data → статья, факты до → после:
    # dt 1 мс — 25 → 25 (seed 42); dt 2 мс — 23 → 25 и 24 → 24 (seed 42 /
    # 7), чтение быстрее на 25%. Стимул 40 мс вместо 60 или пауза 50 мс
    # вместо 150 — хуже (21/36). Числа других [замер] мерились при 1 мс.
    dt_ms: float = 2.0
    # Верхняя граница доли нейронов, стреляющих за один шаг
    # (размер event-таблицы). Лишние спайки теряются и считаются в /stats.
    # [замер] 1% — терялись сотни тысяч спайков за проход (залпы рабочей
    # памяти до 30% зоны за 1 мс, ещё до τsyn 5 мс). После устранения
    # залпов, при чтении на 100k: медиана 0.03%, 99.9% шагов < 1.02%,
    # максимум 1.54%. 2% — с запасом; 5% тормозило большие мозги
    # (200k: 7 ток/с — шаг тратит время на пустые строки таблицы).
    max_spike_fraction: float = 0.02
    # [замер] пик за шаг: 2k нейронов — 16.9%, 20k — 7.9%, 100k — 1.5%.
    # Поэтому не меньше 2000 строк (но не больше 20% мозга): tiny —
    # 400 (20%), 20 тыс. — 2000 (10%), 100k+ — 2%.
    min_spike_table: int = 2000
