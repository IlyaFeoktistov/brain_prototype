@dataclass
class AreaSpec:
    """
    Зона мозга (анатомия — brain/anatomy.py): колонка коры по слоям (имя в
    BrainConfig.layered_areas) или ядро — главные клетки E и местные
    тормозные I.
    """

    name: str
    title: str
    # Доля от размера мозга (колонка — не меньше min_column_neurons). 0 —
    # число клеток задаёт cells.
    share: float = 0.0
    # Число главных клеток ядра по данным (реле — по рецепторам органа,
    # гиппокамп — по разреженности связей). 0 — по доле.
    cells: int = 0
    # Связь E → E слоя 2/3 колонки учится (STDP) — modulator как у путей.
    ee_plastic: bool = False
    ee_modulator: str = "dopamine"
    # STDP связей внутри зоны симметричное: потенциируют оба порядка спайков
    # (CA3 → CA3, Mishra et al. 2016).
    ee_symmetric: bool = False
    # Торможение к E-клетке зоны растёт с её частотой (inh_gain_per_spike).
    inhibition_adapts: bool = False
    # Своя адаптация главных клеток ядра, мВ за спайк; None — общая (e_adapt_b).
    adapt_b: float | None = None
    # Пейсмейкер: частота без входа (в срезе), Гц — ток покоя ставится так,
    # чтобы клетка сама стреляла с этой частотой. 0 — нет.
    autonomous_hz: float = 0.0
    # Ядро: доля местных тормозных клеток (0 — их нет) и местные связи по
    # данным: (входов E → I, ВПСП мВ, входов I → E, ТПСП мВ, входов I → I,
    # ТПСП мВ, частота тормозных Гц[, входов E → E, ВПСП мВ]) — anatomy.NUCLEI.
    local_inhibitory: float = 0.0
    local_psp: tuple = ()
    # Своё окно STDP у клеток зоны (мс; Bi & Poo 1998 — ~20 мс); None —
    # общее (BrainConfig.stdp_*).
    stdp_tau_plus: float | None = None
    stdp_ltp_rise: float | None = None
    stdp_tau_minus: float | None = None
    # Свои множители согласования колонки (14 чисел, как BrainConfig.
    # column_gain_*) — для стенда подбора, где в одной сети живут копии
    # колонки. () — общие.
    column_gains: tuple[float, ...] = ()


@dataclass
class SensorSpec:
    """
    Орган-датчик (разъём тела): свой участок рецепторов и зона, куда он
    входит. Мозг знает только свои клетки; что рецепторы чувствуют — дело
    органа (улитка, сетчатка), откуда сигнал — дело мира.

    wiring = "random"     клетка зоны берёт k случайных рецепторов
    wiring = "tonotopic"  ухо: клетка L4 — своё место на оси частот
    wiring = "oriented"   сетчатка → V1: простая клетка собирает входы,
                          выстроенные в линию (engine._wire_oriented)
    wiring = "map"        по положению: клетки зоны стоят вдоль поля по
                          порядку, клетка берёт k рецепторов у своего места
    """

    name: str
    area: str
    size: int
    k: int
    # Вес рецептора на клетке зоны (без реле); у органов с реле вес пути
    # таламус → L4 — по данным (engine, _thalamic_path), здесь только знак.
    weight: float
    inhibitory_gain: float = 1.0
    # Сетка рецепторов (сетчатка): строки × столбцы одного слоя, слоёв ON и
    # OFF два. 0 — без геометрии.
    rows: int = 0
    cols: int = 0
    wiring: str = "random"
    # Реле таламуса: рецепторы → его клетки один к одному, оттуда — в L4
    # зоны. "" — прямо в зону.
    relay: str = ""
    # Ядра между органом и реле по порядку (слух: кохлеарное ядро, нижнее
    # двухолмие) — engine._brainstem; () — орган прямо в реле.
    brainstem: tuple[str, ...] = ()
    # Рецепторы стреляют и в тишине, Гц. 0 — нет.
    spontaneous_hz: float = 0.0
    # ВПСП рецептора на клетке зоны, мВ; None — weight как есть.
    psp_mv: float | None = None


@dataclass
class PathwaySpec:
    """
    Проводящий путь между зонами по данным. Вес — из измеренного PSP
    (psp_mv) или, между колонками коры, из доли межзонных входов
    (engine._cortical_path); таламус → колонка — engine._thalamic_path.
    """

    src: str
    dst: str
    # Строится входов на клетку; у путей с k_data — меньше, чем по данным
    # (вес × √(k_data / k), недостающее — средним полем).
    k: int
    plastic: bool = False
    cap: float = 2.0
    # Кто превращает след STDP в вес (engine.chemical_plasticity):
    # "hebbian" — сразу (кора), "acetylcholine" — занятость рецепторов
    # ацетилхолина (гиппокамп), "dopamine" / "dopamine_d2" — фазный дофамин
    # (стриатум D1 / D2), "climbing" — лазающее волокно (мозжечок).
    modulator: str = "dopamine"
    # Передачу по пути подавляет ацетилхолин (Hasselmo 1995).
    ach_suppressed: bool = False
    # Топографический путь: получатель собирает k входов с круга на карте
    # источника вокруг своей проекции; площадь круга — topographic × k
    # клеток. 0 — входы со всей зоны случайно.
    topographic: float = 0.0
    # Ступень зрительного пути: окно поля (px), с которого клетка берёт
    # входы (engine._retinotopic_pre). 0 — нет.
    retinotopic: float = 0.0
    # Путь по карте реле таламуса (имя реле, «lgn»): обе стороны стоят на
    # карте органа этого реле (engine._relay_place), клетка берёт k
    # ближайших по месту входов (engine._lgn_local). "" — нет.
    mapped: str = ""
    # Своё имя пути (по умолчанию «src -> dst»).
    name: str = ""
    # PSP одного входа, мВ (знак — знак синапса); None — путь между
    # колонками (engine._cortical_path).
    psp_mv: float | None = None
    # Направление по слоям (BrainConfig.pathway_directions): "ff", "fb",
    # "lateral", "thalamic", "ct" (из L6 коры); "" — из таблицы.
    direction: str = ""
    # Обучаемый путь между колонками: входов и PSP — по данным, веса учатся.
    learned: bool = False
    # Входов на клетку по данным (0 — k как есть).
    k_data: float = 0.0
    # Ветка пути на местные тормозные клетки получателя (прямое торможение):
    # входов на тормозную клетку по данным и PSP, мВ. 0 — нет.
    k_data_inhibitory: float = 0.0
    psp_inhibitory_mv: float = 0.0


@dataclass
class BrainConfig:
    # ------------------------------------------------------------------
    # Железо и шаг
    # ------------------------------------------------------------------
    device: str = os.environ.get("BRAIN_DEVICE", "auto")  # auto | cuda | cpu
    # Собрать шаг симуляции torch.compile (слить мелкие ядра). Первый
    # запуск дольше (компиляция).
    compile_step: bool = os.environ.get("BRAIN_COMPILE", "1") == "1"
    # Процедурная проводка (brain/wiring.py): врождённые пути с постоянным
    # весом не хранятся — получатели вычисляются хешем в шаге. Размен памяти
    # на скорость; задаётся при создании мозга.
    procedural_wiring: bool = False
    # Задержки путей по типу (кольцо в engine; все входы — возбуждение,
    # торможение, NMDA, дендрит): от спайка до тока. Внутри зоны — синапс +
    # местный аксон ~1 мс [сверить по латентностям пар Campagnola 2022];
    # кора → кора 6 мс (Swadlow; Caminiti et al. 2013); таламус → кора ~2 мс
    # (Swadlow 1995: 1.5–2.5); кора → ядра, ядра ↔ ядра — 2 мс [сверить].
    # Выкл. — всё через шаг (dt).
    path_delays: bool = False
    delay_local_ms: float = 1.0
    delay_cortical_ms: float = 6.0
    delay_thalamocortical_ms: float = 2.0
    delay_subcortical_ms: float = 2.0
    seed: int = 42
    # Шаг 0.5 мс: при нём согласован фон (nucleus_bias_mv,
    # column_gain_external_pop — tools/anatomy_fit.py) и быстрые синапсы
    # (τ 5 мс) идут гладко.
    dt_ms: float = 0.5
    # Верхняя граница доли нейронов, стреляющих за один шаг (путь PyTorch).
    max_spike_fraction: float = 0.02
    # Ёмкость списка событий за шаг для пути PyTorch: доля синапсов таблицы;
    # не вместившееся теряется (dropped → event_overflow). Быстрые ядра
    # буфера не используют — идут по строкам таблицы выстреливших и ничего
    # не теряют (tools/kernel_check.py).
    event_capacity: float = 0.02
    # Переполнение таблицы событий: "error" — прогон останавливается,
    # "warn" — печать (диагностика). Молча — никогда.
    event_overflow: str = "error"
    # Не меньше стольких строк в таблице шага (но не больше 20% мозга).
    min_spike_table: int = 2000

    # ------------------------------------------------------------------
    # Размер и анатомия (зоны и пути — brain/anatomy.py)
    # ------------------------------------------------------------------
    size: str = os.environ.get("BRAIN_SIZE", "small")
    areas: list[AreaSpec] = field(default_factory=list)
    pathways: list[PathwaySpec] = field(default_factory=list)

    # ------------------------------------------------------------------
    # Клетки колонки — человек, тип по транскриптому (patch-seq; Allen
    # Synaptic Physiology r2.1, MTG, медианы): IT L2/3 n 39, PVALB 43, SST 42,
    # VIP 22, LAMP5/PAX6 57. Мышь для сравнения: E τm 20.4, PV 7.0, SST
    # 19.5, VIP 13.3 мс.
    # ------------------------------------------------------------------
    # Мембрана, мс.
    column_e_tau_m: float = 19.6
    # PV человека, слой 2/3 (Bakos et al. 2025,
    # https://doi.org/10.1371/journal.pbio.3003549, n 60): Ri 188 МОм,
    # реобаза 87 пА — до порога ≈ 16.4 мВ (у нас 17.0); «кажущаяся τ» 7.2 мс
    # мерилась деполяризующим шагом (открываются K-каналы), не пассивная τm.
    pv_tau_m: float = 13.0
    som_tau_m: float = 18.4
    vip_tau_m: float = 17.7
    lamp5_tau_m: float = 20.0
    # От покоя до порога, мВ: реобаза × входное сопротивление (те же клетки).
    column_e_gap_mv: float = 18.2
    pv_gap_mv: float = 17.0
    som_gap_mv: float = 21.1
    vip_gap_mv: float = 16.1
    lamp5_gap_mv: float = 16.4
    # Клетки разные: разброс расстояния до порога между клетками, σ мВ —
    # межквартильный размах / 1.35. Тормозные — по типу (synphys patch-seq:
    # PVALB n 29 — 6.7, SST n 25 — 11.0, VIP n 16 — 10.6, LAMP5 n 43 — 8.0);
    # E — по большой выборке Allen Cell Types (человек, n 321; в synphys IT
    # L2/3 n 22 — 8.3). Без разброса популяция переключается разом «все
    # молчат / все стреляют»; с ним частоты распределены широко, как in vivo
    # (логнормально — Buzsáki & Mizuseki 2014). У ядер — то же σ, что у E.
    column_gap_sd_mv: tuple[float, ...] = (4.0, 6.7, 11.0, 10.6, 8.0)  # E, PV, SOM, VIP, LAMP5
    # Адаптация частоты, индекс Allen. Ток адаптации — e_adapt_b × индекс /
    # e_adaptation_index (индекс E мыши 0.034 — к нему относится e_adapt_b).
    # Человек, по типу (synphys patch-seq, медианы): IT L2/3 0.097, PVALB
    # 0.041, SST 0.033, VIP 0.060, LAMP5/PAX6 0.051.
    e_adaptation_index: float = 0.034
    column_e_adaptation_index: float = 0.097
    pv_adaptation_index: float = 0.041
    som_adaptation_index: float = 0.033
    vip_adaptation_index: float = 0.060
    lamp5_adaptation_index: float = 0.051
    # Связи внутри зоны: (от, к, вероятность, PSP в покое, мВ). Вероятность —
    # найдено / проверено пар, L2/3 мыши (Campagnola et al. 2022, Fig. 2B);
    # PSP — Fig. 3D (у тормозных — по всем слоям). Сырые числа без поправки
    # на срезанные аксоны (+30–50% у E, до ×3 у I) — нижняя граница.
    # Сходится с Pfeffer 2013: PV → E и PV, SOM → все кроме себя, VIP → SOM.
    # SOM → E — на дендриты (ветки), остальные — на сому.
    # LAMP5 (нейроглиаформные; у мыши в synphys нет, у человека — patch-seq):
    # E → LAMP5 4 из 11 пар (0.36). LAMP5 → любые — 0.87: GABA действует
    # объёмно, гиперполяризация у 178 из 204 соседей ближе 100 мкм, хотя
    # классический синапс — лишь у 22% варикозностей (Oláh et al. 2009; в
    # synphys синаптических пар 2 из 10). Медленные IPSP — на всех типах
    # (Oláh et al. 2007). К LAMP5: SOM → LAMP5 −0.29 мВ (1 пара, synphys),
    # вероятности — как к VIP (тоже клетки CGE) [сверить]. LAMP5 — вне
    # нормировки по Potjans (engine._wire_column): его данные — объёмное
    # действие, которого в синаптических парах Potjans нет.
    local_links: tuple[tuple[str, str, float, float], ...] = (
        ("E", "PV", 0.42, 0.27), ("E", "SOM", 0.30, 0.09), ("E", "VIP", 0.20, 0.56),
        ("E", "LAMP5", 0.36, 0.30),
        ("PV", "E", 0.35, -0.44), ("PV", "PV", 0.38, -0.47), ("PV", "SOM", 0.07, -0.25),
        ("SOM", "E", 0.23, -0.16), ("SOM", "PV", 0.16, -0.18), ("SOM", "SOM", 0.03, -0.17),
        ("SOM", "VIP", 0.39, -0.17), ("SOM", "LAMP5", 0.39, -0.29),
        ("VIP", "E", 0.06, -0.06), ("VIP", "PV", 0.02, -0.13), ("VIP", "SOM", 0.15, -0.15),
        ("VIP", "VIP", 0.01, -0.14), ("VIP", "LAMP5", 0.01, -0.14),
        ("PV", "LAMP5", 0.07, -0.25),
        ("LAMP5", "E", 0.87, -0.83), ("LAMP5", "PV", 0.87, -0.83), ("LAMP5", "SOM", 0.87, -0.83),
        ("LAMP5", "VIP", 0.87, -0.83), ("LAMP5", "LAMP5", 0.87, -0.83),
    )
    # Синапс LAMP5 — медленный (ГАМК-А медленный + ГАМК-Б): у человека спад
    # IPSP ~100 мс (synphys: 101 и 90 мс), полуширина ~230 мс (Oláh 2007),
    # у PV — ~5 мс. Ток синапса спадает за lamp5_tau_syn.
    lamp5_tau_syn: float = 100.0
    # Второе, медленное состояние синапса LAMP5 — десенситизация ГАМК-А
    # рецепторов долгим облаком GABA (Karayannis et al. 2010, NGFC
    # гиппокампа): после 100 спайков по 0.1 Гц спад с τ 21.9 и 239 с,
    # восстановление на 50% за 143 с (n 26) — τ 143 / ln 2 ≈ 206 с; спад
    # 1/21.9 с = 1/206 с + U·0.1 Гц — U ≈ 0.41. [Гиппокамп и аутапсы — у коры
    # человека не измерено.]
    lamp5_desens_tau_s: float = 206.0
    lamp5_desens_u: float = 0.41
    # NMDA в возбуждающих синапсах на клетки E колонок. Человек, L2/3 MTG
    # (Hunt et al. 2023): блокатор NMDA уменьшает единичный EPSP на 23% (n 7)
    # и его спад на 17% — сила NMDA такая, чтобы при −70 мВ он давал 23%
    # пика. Блок магнием — Jahr & Stevens 1990: 1 / (1 + [Mg]/3.57 ·
    # e^(−0.062·V)), Mg 1 мМ. Спад 20 мс — эффективный у сомы (пик +23% и
    # спад ×1.2 вместе; сам ток NMDA спадает 50–150 мс).
    # Пока выключено: только у клеток E NMDA сдвигает баланс к возбуждению —
    # одиночная колонка держит, целый мозг вспыхивает (L2/3 120–285 Гц,
    # гиппокамп 400). Нужен NMDA и на тормозных (у PV меньше, у SST больше)
    # [данные — найти] — тогда включить.
    nmda: bool = False
    nmda_share_at_rest: float = 0.23
    nmda_tau_ms: float = 20.0
    mg_mm: float = 1.0
    # Среднее поле недостающих соседей — сглаживание частоты источника, мс
    # (engine._build_mean_field): дольше периода гамма-ритма (20–40 мс),
    # чтобы быстрые колебания построенных клеток не шли всем общим входом.
    mean_field_tau_ms: float = 50.0
    # Связь падает с расстоянием по Гауссу (σ, мкм: E → I 99, I → E 96, I → I
    # 131, E → E 124.6 — Campagnola Fig. 2A; E → E pmax 0.05 по 5467 парам).
    # Число входов — из вероятностей Potjans, σ выбирает партнёра на листе
    # коры (column_geometry).
    sigma_ei_um: float = 99.0
    sigma_ie_um: float = 96.0
    sigma_ii_um: float = 131.0
    sigma_ee_um: float = 124.6
    # Колонки без карты — лист коры (engine._sheet_pre): местные связи
    # выбираются по расстоянию; False — случайно по всей зоне, только для
    # сравнения (DESIGN «Лист коры»).
    column_geometry: bool = True
    # Кратковременная пластичность синапсов по парам типов (Tsodyks & Markram
    # 1997, с облегчением — Markram et al. 1998): (от, к, U, восстановление
    # мс, облегчение мс; 0 — нет). Человек (Allen synphys r2.1, медианы по
    # парам A2/A1, A6–8/A1 серии 50 Гц и A9/A1 через 250 мс; Tsodyks–Markram
    # по сетке): E → E (n 122) 0.99 / 0.55 / 1.17 — U 0.5, 60, 200 мс, у нас
    # ≈; E → тормозные (n 34, в основном быстрые) 0.92 / 0.45 / 0.98 — U
    # 0.45, 80, 50; I → E (n 16) 0.75 / 0.40 / 0.87 — U 0.25, 150, 0 ≈; I → I
