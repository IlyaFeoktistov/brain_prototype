@dataclass
class BrainConfig:
    # ------------------------------------------------------------------
    # Железо
    # ------------------------------------------------------------------
    device: str = os.environ.get("BRAIN_DEVICE", "auto")  # auto | cuda | cpu
    # Собрать шаг симуляции torch.compile (слить мелкие ядра). Первый
    # запуск дольше (компиляция). [замер — см. DESIGN «Скорость шага»]
    compile_step: bool = os.environ.get("BRAIN_COMPILE", "1") == "1"
    # Процедурная проводка (brain/wiring.py): врождённые пути с постоянным
    # весом (~41% синапсов) не хранятся — получатели вычисляются хешем в
    # шаге. Задаётся при создании мозга. Размен памяти на скорость:
    # [замер] 20 тыс. нейронов — память −30% (60 → 42 МБ), чтение −23%
    # (65.8 → 50.4 ток/с), факты 24 → 27 (шум). Включать для больших
    # мозгов, когда упираются в видеопамять.
    procedural_wiring: bool = False
    seed: int = 42
    # [не подбиралось] 1 мс: стандарт для LIF/AdEx с Эйлером.
    # [замер] 20 тыс., 2 прохода train-data → статья, факты до → после:
    # dt 1 мс — 25 → 25 (seed 42); dt 2 мс — 23 → 25 и 24 → 24 (seed 42 /
    # 7), чтение быстрее на 25%. Стимул 40 мс вместо 60 или пауза 50 мс
    # вместо 150 — хуже (21/36). Числа других [замер] мерились при 1 мс.
    dt_ms: float = 2.0
    # Верхняя граница доли нейронов, стреляющих за один шаг
    # (размер event-таблицы). Лишние спайки теряются и считаются в /stats.
    # [замер] 1% — терялись сотни тысяч спайков за проход (залпы рабочей
    # памяти до 30% зоны за 1 мс, ещё до τsyn 5 мс). После устранения
    # залпов, при чтении на 100k: медиана 0.03%, 99.9% шагов < 1.02%,
    # максимум 1.54%. 2% — с запасом; 5% тормозило большие мозги
    # (200k: 7 ток/с — шаг тратит время на пустые строки таблицы).
    max_spike_fraction: float = 0.02
    # [замер] пик за шаг: 2k нейронов — 16.9%, 20k — 7.9%, 100k — 1.5%.
    # Поэтому не меньше 2000 строк (но не больше 20% мозга): tiny —
    # 400 (20%), 20 тыс. — 2000 (10%), 100k+ — 2%.
    min_spike_table: int = 2000
    # Отвергнутые варианты [замер]: таблицы разного размера под пик
    # прошлых 10 мс — теряли сотни тысяч спайков на начале слов;
    # точный список спайков без CUDA Graph — медленнее
    # (300k: 6 ток/с против 9, 100k: 10 против 25).

    # ------------------------------------------------------------------
    # Размер и анатомия.
    # ------------------------------------------------------------------
    size: str = os.environ.get("BRAIN_SIZE", "small")
    # [биология] ~20% тормозных нейронов в неокортексе.
    inhibitory_fraction: float = 0.20
    areas: list[AreaSpec] = field(default_factory=default_areas)
    pathways: list[PathwaySpec] = field(default_factory=default_pathways)

    # Локальные связи с торможением внутри каждой зоны.
    # [замер] ei=1, ie=-2: синхронные залпы до 100% зоны;
    # ei=3, ie=-6..-8: зоны молчали. 2 / -4 — рабочая точка, дальше
    # возбудимость доводит гомеостаз.
    k_ei: int = 50
    k_ie: int = 50
    k_ii: int = 25
    ei_weight: float = 2.0
    ie_weight: float = -4.0
    ii_weight: float = -1.5

    # ------------------------------------------------------------------
    # Нейроны (мВ, мс). Cortex E — AdEx, I — быстрый LIF,
    # memory E — LIF с медленным NMDA-подобным током.
    # ------------------------------------------------------------------
    # [биология] τm, порог, покой, сброс — типичные для пирамидных клеток.
    e_tau_m: float = 20.0
    # [замер] AMPA/GABA 2 мс -> синхронные залпы (до 929 из 3200 нейронов
    # рабочей памяти за 1 мс); 5 мс [биология] — залпов нет.
    e_tau_syn: float = 5.0
    e_delta_t: float = 2.0
    # [биология] спайковая адаптация пирамидных клеток.
    e_adapt_tau: float = 150.0
    e_adapt_b: float = 1.0
    i_tau_m: float = 10.0
    # Быстрые интернейроны (PV) ближе к порогу, чем пирамидные клетки:
    # торможение должно успевать раньше залпа E.
    # [замер] без этого ассоциативная зона копила вход ~25 мс и давала
    # залп (158 из 8000 за 1 мс), торможение приходило уже после.
    i_excitability: float = 8.0
    i_tau_syn: float = 5.0
    # [биология] NMDA ~100-400 мс. При 70 мс на слово 400 мс — след
    # нескольких последних слов.
    memory_tau_syn: float = 400.0
    # Медленный ток рабочей памяти относительно быстрого.
    # [замер] 1.0 — память не успевала зарядиться за 2 слова пробы;
    # 0.5 — заряжается. Вариант «почти без быстрого тока» (AMPA 0.1,
    # NMDA 1.5, чтобы память держала прошлое, а не текущее слово)
    # дал +0.02 MRR на неоднозначных переходах — в пределах шума.
    memory_nmda_ratio: float = 0.5
    memory_ampa_ratio: float = 1.0
    memory_tau_m: float = 20.0
    v_rest: float = -70.0
    v_threshold: float = -50.0
    v_reset: float = -58.0
    refractory_ms: float = 2.0

    # Гомеостаз возбудимости (intrinsic plasticity): после каждого слова
    # возбудимость зоны (ток покоя, мВ) сдвигается к target_activity.
    # [замер] ручная подгонка весов без него стояла «на лезвии» —
    # зона либо молчала, либо взрывалась. С ним — 4-5% в каждой зоне.
    # Скорость 0.5 мВ и пределы [не подбиралось].
    homeostasis_rate: float = 0.5
    homeostasis_bias_range: tuple[float, float] = (-10.0, 18.0)
    # «Пренатальная» калибровка: столько случайных звуков мозг
    # слышит при рождении. [замер] 400 и 1000 дают одинаковую
    # рабочую точку; 400 — 3.5 с.
    calibration_tokens: int = 400

    # Фоновый шум: Poisson-вход на каждый нейрон.
    background_rate_hz: float = 1000.0
    # [замер] 0.5 — ансамбль слова в смысловой зоне почти случаен
    # (сходство повторов 0.07); 0.2 — 0.43; 0.1 — 0.57.
    background_weight: float = 0.1
    # [не подбиралось] рабочей памяти шум нужнее: её нейроны висят
    # у порога на тоническом NMDA-токе. Залпы он не убрал (их убрали
    # τsyn 5 мс + торможение), но и не мешает.
    memory_background_weight: float = 0.3

    # ------------------------------------------------------------------
    # Пластичность: STDP -> eligibility trace -> dopamine.
    # Вес меняется только когда приходит dopamine.
    # ------------------------------------------------------------------
    # Ядро LTP со сдвигом: exp(-t/80) - exp(-t/30), пик через ~45 мс.
    # Одновременные спайки (одно слово) почти не усиливаются, спайк
    # ~одно слово назад — сильнее всего (time-lagged Hebbian, медленная
    # кинетика NMDA).
    # [замер] главное улучшение памяти: место правильного слова из
    # идеального ансамбля [113, 54, 61, 2, 198 …] -> [10, 1, 18, 3, 6 …]
    # из 270; угадывание при чтении 10% -> 24%.
    stdp_tau_plus: float = 80.0
    stdp_ltp_rise: float = 30.0
    # [замер] окно сбалансировано с перевесом депрессии
    # (Song/Miller/Abbott 2000). При A- = 0.004, τ- = 20 (перекос в
    # LTP в 5 раз) треть синапсов росла без причины.
    stdp_tau_minus: float = 40.0
    stdp_a_plus: float = 0.010
    stdp_a_minus: float = 0.012
    # Сколько живёт след для дофамина.
    # [замер] 1500 мс (~20 слов): мозг учил «какие слова рядом в тексте»,
    # а не «что идёт следом». 200 мс (~3 слова) — закрепляется
    # именно последний переход. 100 мс не лучше.
    eligibility_tau: float = 200.0
    # [замер] 3.0 — хуже, 0.3-0.5 — без явного выигрыша.
    dopamine_learning_rate: float = 1.0

    # Выученное = рост веса относительно веса при рождении.
    # [замер] на трёх зёрнах разница в шуме (MRR 0.42 против 0.45);
    # оставлено как более честное определение.
    learned_from_birth: bool = True
    # Вклад рабочей памяти в ожидание.
    # [замер] со случайной проводкой (три зерна, MRR фактов / контекста):
    #   без вклада 0.564 / 0.303, gain 0.5 0.506 / 0.265, 1.0 — хуже.
    # [замер] с местами слов в памяти и ростом синапсов от контекста
    # (20 тыс., seed 42, 36 фактов train-data, первое слово / в тройке):
    #   без вклада             25 / 25
    #   add 0.25 / 0.5 / 1.0   17 / 22, 14 / 19, 10 / 19 — контекст
    #                          перебивает слово («солнце является» → «свет»)
    #   gain 0.5 … 4.0         25 / 26–27 — контекст выбирает среди
    #                          кандидатов текущего слова («звездой» 3-я)
    context_gain: float = 2.0
    # Как контекст входит в ожидание: "add" | "gain" (умножает отклик
    # на текущее слово — конъюнкция «X, потом Y»).
    context_mode: str = "gain"
    # Правило обучения путей ИЗ рабочей памяти:
    #   "stdp"       — как у коры (порядок спайков);
    #   "covariance" — (активность пре − средняя по зоне) × спайк поста.
    # [замер] covariance не лучше stdp (MRR памяти 0.164 против 0.18).
    context_rule: str = "stdp"
    context_hebb_gain: float = 1.0
    # Контекст как конъюнкция в самих нейронах (дендритное NMDA-плато):
    # синапсы «рабочая память → смысл» приходят на дальний дендрит и
    # клетку сами не возбуждают, а усиливают её возбуждающий вход:
    #     вход × (1 + dendrite_gain · плато),
    #     плато = i_dend / (i_dend + dendrite_half_mv).
    # То же, что режим gain у формулы ожидания, но в спайках — нужно,
    # чтобы слово выбирали нейроны (ROADMAP P0 «без if-else»).
    # [не подбиралось] gain 2 — как context_gain; τ 100 мс — плато NMDA.
    # [замер] 100 тыс., 2 прохода train-data: выбор слова спайками (гонка к
    # порогу) 10/26 → 17/26, молчит 8 → 2; но формула ожидания (она пока
    # отвечает в чате) 25/36 → 15/36 — рассчитана на сложение контекста.
    # С ответом нейронами (neural_speech) — на уровне прежней схемы, см. там.
    dendritic_context: bool = True
    # Ответ нейронами (ROADMAP P0): на последнем слове реплики и на каждом
    # своём слове открыты ворота «говори» — ровный ток speak_gate_mv всей
    # смысловой коре (растормаживание из базальных ганглиев через
    # таламус). Слово — место, выстрелившее само; никто — молчание; место
    # «.» — мысль кончилась. Без decode, порогов и таблицы уверенности.
    # [замер] 100 тыс. с дендритами, факты одним словом (26): ворота
    # 10 мВ — 15 верно, молчит 9; 16 — 17, молчит 2; 18 — 17, молчит 0,
    # активна 0.25% зоны; 22 — зона вспыхивает целиком.
    # [замер] итог, 2 зерна (42 / 7), факты первым словом (36): прежняя
    # схема (формула, контекст складывается) 25 / 24; дендриты + нейроны
    # (затухание 0.95, своя речь не в памяти): ворота 16 — 26 / 21,
    # «не знаю» 3–8%; 17 — 25 / 21; 18 — 25 / 24, «не знаю» 0%, но покой
    # (−67.5) + 18 = −49.5 мВ — ровно порог: без подготовки стреляет шум,
    # мозг болтает наугад («мне скучно» → «рим»), и болтовня учится —
    # после 8 раз «мне скучно» в скуке начинал с «воду». На 16 клетки
    # без подготовки остаются ниже порога: незнакомое — «не знаю».
    # Ворота на эхе слова без обучения — 21–20 при 18–20 мВ, хуже.
    neural_speech: bool = True
    # Неожиданность (ошибка предсказания → дофамин → обучение) — из самих
    # нейронов: насколько место пришедшего слова было подготовлено
    # (потенциал его клеток в конце прошлого слова) против самого
    # подготовленного места; без формулы ожидания. [замер] 100 тыс.
    # нейронов, чтение train-data: место слова — самое подготовленное в
    # 26% слов (формула угадывает 30%), решения совпадают в 76%.
    neural_surprise: bool = False
    # Неожиданность 0 — место подготовлено сильнее всех, 1 — не выше этой
    # доли мест (квантиль потенциала). [замер] 100 тыс., чтение train-data
    # на обученном мозге: база-медиана — ошибка мягче формулы (медиана 0.5
    # против 0.88, дофамин 1.9 против 3.2), обучение 24 → 10 фактов из 36;
    # база 0.97 — медиана 0.97, дофамин 3.5, корреляция с формулой 0.58.
    # Seed 7 (формула 24): 0.9 — 9, 0.97 — 19, 0.99 — 21 — паритета нет,
    # поэтому выключено (DESIGN «Неожиданность из нейронов»).
    neural_surprise_base: float = 0.97
    speak_gate_mv: float = 16.0
    # Ворота после каждого своего слова × speak_gate_decay (порыв
    # сказать удовлетворяется) — мысль идёт, пока предсказание сильное.
    # [замер] seed 42 (ворота 16): 1.0 — 23, мысль не кончается
    # («москва россия москва россия…»); 0.95 — 26, «рим → италия»,
    # «москва → россия»; 0.9 — 22; 0.85 — 24, ответы короче.
    speak_gate_decay: float = 0.95
    # Пул быстрого торможения смысловой коры (PV-корзинчатые клетки
    # плотно слушают все соседние пирамиды): каждый спайк зоны тормозит
    # все её E-клетки на pool_inhibition_mv, затухает за τ мс. Победило
    # одно место — остальные прижаты (конкуренция мест, «победитель один»).
    # [замер] без пула при открытых воротах стреляют 5–6 мест сразу, все
    # уходят в рабочую память — мысль уплывает. 0 — пула нет.
    # [замер] 100 тыс. с дендритами, ответ нейронами, факты первым словом
    # (36): без пула 23; пул 0.5 / 1 / 2 мВ при воротах 16 — 23 / 20 / 23,
    # при воротах 20–24 — 11–17; повторы и уплывание те же. Не помогает:
    # мысли не хватает цели, а не конкуренции. Выключен.
    # Своя речь в рабочей памяти: 1 — как услышанная (вытесняет вопрос),
    # 0 — не входит (подавление своей речи эфферентной копией).
    # [замер] seed 42, ворота 16: 1 — 23, 0.3 — 23, 0 — 24; повторы те же.
    own_speech_memory: float = 0.0
    pool_inhibition_mv: float = 0.0
    pool_inhibition_tau_ms: float = 5.0
    dendrite_gain: float = 2.0
    dendrite_half_mv: float = 2.0
    dendrite_tau_ms: float = 100.0
    # Ветки дендрита: у пирамидной клетки плато загорается на отдельной
    # ветке, когда на неё вместе пришло несколько входов (Poirazi;
    # Harvey & Svoboda 2007: синапсы, окрепшие вместе, кучкуются на одной
    # ветке). Синапсы памяти и цели, выросшие на одной неожиданности
    # («столица» + «франции» → «Париж»), ложатся на одну ветку; врождённые —
    # на случайные. Плато ветки = сигмоида (ток ветки − порог) / крутизна,
    # клетка берёт самую горячую ветку. 1 — одна ветка, прежнее
    # насыщение (dendrite_half_mv). Числа — DESIGN «Ветки дендрита».
    dendrite_branches: int = 4
    dendrite_threshold_mv: float = 10.0
    dendrite_slope_mv: float = 2.0

    # Homeostatic synaptic scaling (Turrigiano): суммарный входной
    # пластичный вес нейрона не больше budget * врождённая сумма.
    # [не подбиралось] 1.5.
    synaptic_scaling_enabled: bool = True
    synaptic_scaling_budget: float = 1.5
    # Раз в 20 фраз (стоит 0.5 мс на 3 млн синапсов — дело не в цене).
    # [замер] каждую фразу лечит эпилептический очаг (факты
    # после вики 0 → 9), но мешает быстрому обучению: бюджет 1.5 урезает
    # все входы, как только выучено несколько сильных связей (тесты
    # «скука → скучно», закрепление сном; бюджет 2–3 — мысль ходит по
    # кругу «париж берлин рим париж»). Очаг лечит базовый контур
    # (base_circuit).
    synaptic_scaling_every: int = 20

    # Базовый контур (docs/ARCHITECTURE.md, «Стабилизаторы»): механизмы,
    # которыми мозг держит ансамбли от зацикливания, — все сразу. Действуют
    # на E зон с обучаемыми связями внутри себя (смысловая кора).
    #  - Истощение синапсов (Tsodyks–Markram): спайк тратит долю stp_u
    #    ресурса пресинапса, ресурс восстанавливается за stp_tau_rec_ms.
    #    [биология] пирамидные клетки: U 0.2–0.5, восстановление 500–800 мс.
    #  - Пластичность торможения на уровне клетки (по Vogels 2011):
    #    каждый спайк усиливает приходящее к клетке торможение на
    #    inh_gain_per_spike, усиление возвращается к 1 за inh_gain_tau_ms.
    #    В равновесии 1 + шаг · τ · частота: 5 Гц — 1.2×, очаг 240 Гц —
    #    ~10×. [биология] секунды; [не подбиралось] шаг 0.004.
    #  - Ослабление во сне (Tononi, гипотеза синаптического гомеостаза):
    #    за каждое проигрывание выученный прирост всех пластичных
    #    синапсов × (1 − sleep_downscale): ночь в 250 проигрываний (50
    #    впечатлений × 5) — ~10%. [не подбиралось] 0.0004.
    # [замер] 20 тыс., 2 прохода train-data → 10 тыс. слов вики, факты
    # первым словом до → после: без стабилизаторов 15 → 0 (эпилептический
    # очаг частых слов, DESIGN «Ёмкость: обвал после чтения»); гомеостаз
    # по частоте (был calm_hz, убран): seed 42 12 → 12, seed 7 16 → 2;
    # базовый контур + адаптация сигнала чувства (interoception_adapt_ms):
    # seed 42 13 → 13, seed 7 11 → 16; очага нет, стенд (/health) чист.
    # DESIGN «Базовый контур».
    base_circuit: bool = True
    stp_u: float = 0.2
    stp_tau_rec_ms: float = 500.0
    inh_gain_per_spike: float = 0.004
    inh_gain_tau_ms: float = 10000.0
    sleep_downscale: float = 0.0004


    # Структурная пластичность: синапс, ослабший ниже
    # prune_fraction × минимальный врождённый вес пути, отмирает,
    # вместо него растёт новый. Проверка раз в N фраз.
    # [замер] абсолютный порог 0.02 совпадал с минимальным весом пути
    # «память -> смысл»: 2 млн синапсов за 3 прохода гибли и росли
