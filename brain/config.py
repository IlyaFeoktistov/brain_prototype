    @classmethod
    def from_dict(cls, data: dict) -> "BrainConfig":
        data = dict(data)
        # Сохранения до понятий: проводка «слух → смысл» в них есть.
        data.setdefault("concepts_enabled", False)
        data.setdefault("ear_letters", False)
        data.setdefault("memory_places", False)

