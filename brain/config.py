    # Гиппокамп и сон (brain/hippocampus.py).
    # [не подбиралось] сколько фраз помнит гиппокамп.
    hippocampus_capacity: int = 50_000
    # Предпочтение неожиданного при проигрывании: 0 — поровну, 1 —
    # пропорционально дофамину фразы.
    # [замер] train-data, 2 зерна, равные вычисления (факты / контекст /
    # угадывание): 3 прохода 0.438 / 0.149 / 0.345; 1 проход + сон
    # с приоритетом 0.253 / 0.298 / 0.360; 1 проход + сон поровну
    # 0.488 / 0.424 / 0.362. Приоритет застревает на трудных фразах.
    replay_priority: float = 0.0
    # Засыпать, когда с мозгом не говорят столько секунд и есть
    # невыученные впечатления. [не подбиралось]
    sleep_when_idle: bool = True
    idle_sleep_seconds: float = 30.0
    # Фраз за одну порцию сна: между порциями мозг проверяет, не
    # пришло ли сообщение (чтобы проснуться за ~1-2 секунды).
    sleep_batch: int = 10
    # Сколько раз проиграть каждое новое впечатление за сон.
    # [замер] 1 проход 150 фраз + сон (факты / контекст / угадывание):
    # 300 проигрываний (2 на фразу) 0.488 / 0.424 / 0.362; 1500 (5) —
    # 0.629 / 0.502 / 0.387; 3000 (10) — 0.592 / 0.292 / 0.360:
    # переучивание — одни фразы вытесняют остальные.
    replays_per_episode: int = 5
    # «Давление сна»: с этого числа новых фраз мозг устал — сонливость,
    # а в тишине засыпает надолго (до конца сна или пока не разбудят).
    # Раньше засыпал при любом новом впечатлении — и «кемарил» после
    # каждой пары реплик. [не подбиралось] 50 фраз.
    sleepy_after_episodes: int = 50
    # При долгом чтении мозг засыпает посреди текста, когда новых
    # впечатлений вдвое больше порога сонливости, высыпается и читает
    # дальше: иначе с забыванием без сна (early_ltp_half_life) длинный
    # текст терял бы всё, кроме последних сотен фраз. [не подбиралось]
    # 100 фраз: при полураспаде 300 до сна доживает ≥ 79% свежего.
    nap_while_reading: bool = True
    nap_after_episodes: int = 100
    # Фраза, давшая во сне меньше дофамина, считается выученной корой
    # и забывается гиппокампом.
    consolidated_salience: float = 1.0

    # Размышление (think): внутренняя речь + проверяющий.
    # [замер] на 14 вопросах train-data (1 проход + сон 300): первое
    # слово верно 5/14 без размышления, 6/14 с проверяющим — правильного
    # слова часто нет среди 20 кандидатов, проверять нечего.
    # [замер] на живом мозге проверяющий принял «компьютеру» на «какая
    # столица россии?»: связь «россии -> компьютеру» в памяти оказалась
    # сильнейшей. Проверка не умнее памяти — пока выключено (/think on).
    thinking_enabled: bool = False
    think_max_steps: int = 20
    # Сколько кандидатов проверять, прежде чем сдаться на этом шаге.
    think_breadth: int = 5
    # Мысль принята, если связь с целью ≥ порога (0.05 ≈ мысль в первых
    # 20 ожиданиях от слова цели или наоборот). [не подбиралось]
    think_accept: float = 0.05

    # Фоновое чтение в вебе: столько фраз за порцию, между порциями
    # мозг отвечает на сообщения. [не подбиралось] ~0.5–1 с на порцию.
    read_portion_sentences: int = 5

    # Живой режим (веб): мозг всё время что-то делает — в тишине
    # размышляет («блуждание мыслей»), иногда заговаривает сам (повод
    # выбирает эмоция) и ждёт ответа. Обычный режим только отвечает.
    live_mode: bool = False
    # Блуждание мыслей: раз в столько секунд тишины. [не подбиралось]
    wander_every_seconds: float = 8.0

    # Инициатива (часть живого режима): заговорить, когда порыв (из
    # потребностей, Emotions.urge) дорос до initiative_urge — а не по
    # таймеру. Не перебивает (initiative_idle_seconds тишины) и не чаще
    # раза в initiative_cooldown_seconds (рефрактерность). Раньше было
    # правило: 45 с тишины и 2 мин между репликами. [не подбиралось]
    initiative_enabled: bool = True
    initiative_urge: float = 0.8
    initiative_idle_seconds: float = 10.0
    initiative_cooldown_seconds: float = 20.0

    # Вспоминание разговора перед ответом: последние N реплик
    # подталкивают ответ; вес реплики падает в recall_decay раз с каждой
    # следующей; recall_gain — сила следа в долях силы ожидания.
    # [замер] 20 тыс., seed 42/7, тема «Поговорим о Франции/Германии/
    # Италии» -> «столица»; город темы первым среди трёх городов:
    #   без вспоминания 2/6; свои ответы тоже вспоминаются — 6/12 при
    #   любой силе (ответ пересказывает все факты и размывает след);
    #   только реплики человека — 8/12 (0.5), 10/12 (1), 12/12 (2).
    # Сила 2 не взята: не мерили, не перебивает ли след факты.
    # Не решено: в сам ответ доходит слабо (начинает с темы 6/12), и после
    # 3 посторонних реплик след тонет (4/12 = угадывание) — 0.5^3.
    # recall_turns 4/8 не различаются: решает затухание, а не окно.
    # Гиппокамп при ответе (комплементарные системы, McClelland 1995):
    # вопрос будит эпизод, куда пришло больше всего активации от его слов
    # (достраивание по части, CA3; вес слова — 1 / число эпизодов с ним,
    # эффект веера), и на каждом слове ответа место следующего слова
    # эпизода получает ток episode_recall_mv × доля активации —
    # подсказка, выбирают нейроны. Поправили один раз — в следующий раз
    # помнит, хотя кора ещё не выучила. Эпизоды, уже перешедшие в кору,
    # гиппокамп забывает (forget_consolidated) — и подсказки нет.
    # Продолжение кончается паузой (граница эпизода), подсказка идёт за
    # сказанным, а не по счёту слов — ответ замолкает, где замолк эпизод
    # (DESIGN «Конец эпизода — конец ответа»).
    # Число — DESIGN «Гиппокамп при ответе».
    episode_recall: bool = True
    episode_recall_mv: float = 8.0
    recall_turns: int = 4
    recall_decay: float = 0.5
    recall_gain: float = 1.0
    recall_own_answers: bool = False

    # Журнал переписки для /reread (последние реплики).
    dialog_log_turns: int = 2000

    # Сила сигнала чувства в лимбической зоне (мВ); каждому чувству —
    # своя группа нейронов (зона делится поровну между чувствами).
    # [замер] 12 мВ × (0.5 + возбуждение): в спокойствии клетки чувства
    # почти не стреляли (0.5% зоны). 22 + 8 × возбуждение — до порога
    # (20 мВ) с запасом.
    interoception_mv: float = 22.0
    interoception_arousal_mv: float = 8.0
    # Сигнал чувства адаптируется, как любой сенсорный вход: в момент, когда
    # чувство возникло (сменилось или мозг «прислушался к себе»), — полная
    # сила, дальше спадает к доле interoception_tonic за
    # interoception_adapt_ms. Половина силы — ниже порога: в длящемся
    # чувстве клетки молчат, слова связываются с чувством в момент его
    # появления, а не со всем, что мозг прочитал, пока оно длилось.
    # [замер] без адаптации чувство держится всё чтение, путь «чувство →
    # смысл» учится толкать все слова текста (`/trace`: «из» получал от
    # чувства ток 85, «париж» от вопроса 47 + 43) — 20 тыс., seed 7, факты
    # до → после 10 тыс. слов вики: 12 → 1. [биология] адаптация —
    # секунды; [не подбиралось] 2 с, 0.5.
    interoception_adapt_ms: float = 2000.0
    interoception_tonic: float = 0.5
    # Сколько мозг «прислушивается к себе» перед тем, как заговорить.
    feel_ms: float = 100.0
    # [замер] без паузы клетки прошлого чувства досрабатывали в окне,
    # и радость «будила» выученное в скуке «скучно».
    feel_settle_ms: float = 50.0

    # Эмоции (brain/limbic.py): складываются из дофамина, похвалы и
    # уверенности; выключено = не обновляются, не показываются и ни на
    # что не влияют.
    emotions_enabled: bool = True

    # Как эмоции влияют на обучение и ответы (0 — не влияют).
    # Возбуждение (норадреналин) усиливает пластичность:
    # Δw × (1 + arousal_plasticity × возбуждение). [не подбиралось]
    # 1.0 — в сильном возбуждении учится вдвое сильнее.
    arousal_plasticity: float = 1.0
    # Эпизод в гиппокампе: значимость × (1 + arousal_salience ×
    # возбуждение) — эмоциональное вытесняется из памяти последним.
    # [не подбиралось]
    arousal_salience: float = 1.0
    # Смелость ответа: порог уверенности generate_min_confidence ×
    # (1 - valence_boldness × настроение). Радость (+1) — порог ниже,
    # говорит смелее и дальше; после ругани (-1) — выше, чаще «не
    # знаю». [не подбиралось] 0.5: порог в пределах 0.075..0.225.
    valence_boldness: float = 0.5

    # Сохранение мозга между запусками.
    save_path: str = os.environ.get("BRAIN_SAVE", "data/brain.pt")
    autosave: bool = True
    # При чтении папок — не чаще раза в N минут: мозг на 300k
    # нейронов весит больше 1 ГБ, а файлов бывает сотня.
    autosave_minutes: float = 10.0

    # Нейрогенез и смерть нейронов (этап 13 roadmap) пока не
    # реализованы: сначала стабильная память и контекст.

    @property
    def total_neurons(self) -> int:
        return PRESETS.get(self.size) or int(self.size)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "BrainConfig":
        data = dict(data)
        # Сохранения до понятий: проводка «слух → смысл» в них есть.
        data.setdefault("concepts_enabled", False)
        data.setdefault("ear_letters", False)
        data.setdefault("memory_places", False)
        # Сохранения до ответа нейронами учились без дендритов: ответ
        # формулой, как раньше (включить можно в «Функциях»).
        data.setdefault("dendritic_context", False)
        # Сохранения до процедурной проводки хранят все синапсы.
        data.setdefault("procedural_wiring", False)
        data.setdefault("neural_speech", False)

        if isinstance(data.get("form_pathway"), dict):
            data["form_pathway"] = PathwaySpec(**data["form_pathway"])
        data["areas"] = [AreaSpec(**a) for a in data.get("areas", [])] or default_areas()
        # Сохранения до появления predictive: путь чувства в них
        # модулирующий, как сейчас (иначе он снова портит ожидания).
        pathways = [
            {"predictive": p["src"] != "limbic", **p} for p in data.get("pathways", [])
        ]
        data["pathways"] = [PathwaySpec(**p) for p in pathways] or default_pathways()

        for key in ("praise_words", "blame_words", "homeostasis_bias_range"):
            if key in data:
                data[key] = tuple(data[key])

        known = cls.__dataclass_fields__
        return cls(**{k: v for k, v in data.items() if k in known})
