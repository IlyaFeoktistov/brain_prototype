    # Клеток на клавишу (тело руки) [сверить: число из прежней схемы].
    hand_cells: int = 8

    # ------------------------------------------------------------------
    # Сохранение
    # ------------------------------------------------------------------
    save_path: str = os.environ.get("BRAIN_SAVE", str(BRAINS / "brain.pt"))
    autosave: bool = True

    @property
    def total_neurons(self) -> int:
        return PRESETS.get(self.size) or int(self.size)

    def sensors(self) -> list[SensorSpec]:
        """Органы-датчики тела: ухо, глаз, боковое зрение, вкус."""

        from brain.body import Cochlea

        return [
            SensorSpec(
                "ear", "auditory", self.sensory_size, self.k_sensory, 1.0, relay="mgn",
                # Нерв идёт не в таламус, а в ствол: кохлеарное ядро → нижнее
                # двухолмие → MGN (Winer & Schreiner 2005).
                brainstem=("cn", "ic"),
                # Вход таламуса в слуховую L4 — по частоте (тонотопия A1).
                wiring="tonotopic",
                # Волокна слухового нерва в тишине: своя у каждого класса
                # (Liberman 1978; body.FIBERS).
                spontaneous_hz=Cochlea.spontaneous(self.sensory_size, self.cochlea_bands),
            ),
            SensorSpec(
                "eye", "visual", 2 * self.retina_rows * self.retina_cols, 40, 1.0,
                rows=self.retina_rows, cols=self.retina_cols, wiring="oriented", relay="lgn",
                # Ганглиозные клетки сетчатки стреляют и без стимула: у
                # макаки поддерживаемая частота P- и M-клеток ~10–30 Гц
                # (Troy & Lee 1994; кошка — Barlow & Levick 1969) — 20 Гц.
                spontaneous_hz=20.0,
            ),
            # Вкус — канал награды и наказания, как у младенца: сладкое
            # будит дофаминовые клетки VTA (через латеральный гипоталамус и
            # PPTg — Schultz 1998), горькое — латеральную уздечку (её залп
            # через RMTg даёт паузу дофамина — Matsumoto & Hikosaka 2007;
            # Jhou et al. 2009). Кнопки учителя «верно» / «неверно» в мире —
            # этот вкус. Вход клетки — 10 рецепторов по 2 мВ [сверить].
            SensorSpec("sweet", "vta", 50, 10, 0.0, psp_mv=2.0),
            SensorSpec("bitter", "lhb", 50, 10, 0.0, psp_mv=2.0),
            SensorSpec(
                "periphery", "colliculus",
                2 * (self.retina_rows // self.periphery_scale) * (self.retina_cols * self.periphery_fields // self.periphery_scale),
                10, 2.0, rows=self.retina_rows // self.periphery_scale,
                cols=self.retina_cols * self.periphery_fields // self.periphery_scale, wiring="map",
                spontaneous_hz=8.0,
            ),
        ]

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "BrainConfig":
        data = dict(data)
        data["areas"] = [AreaSpec(**a) for a in data["areas"]]
        data["pathways"] = [PathwaySpec(**p) for p in data["pathways"]]
        return cls(**data)
