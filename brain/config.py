@dataclass
class AreaSpec:
    """
    Зона мозга.

    kind = "cortex"  E (AdEx) + I (быстрый LIF), быстрые синапсы
    kind = "memory"  E с медленным NMDA-подобным током (рабочая память)
    share           доля от общего числа нейронов
    """

    name: str
    title: str
    share: float
    kind: str = "cortex"
    # Локальные связи внутри зоны. [не подбиралось] 50 входов.
    k_ee: int = 50
    ee_plastic: bool = True
    # [биология] врождённые связи слабые и случайные: сильные
    # должны появиться только от опыта.
    ee_weight: tuple[float, float] = (0.05, 0.20)
    ee_cap: float = 3.0
    # Целевая доля E-нейронов, отвечающих на слово.
    # [биология] в коре на стимул отвечают единицы процентов клеток.
    target_activity: float = 0.04
    # Своя адаптация E-нейронов: мВ за спайк и время затухания (мс);
    # None — как у коры.
    adapt_b: float | None = None
    adapt_tau: float | None = None
    # Торможение к клетке растёт с её спайками (пластичность торможения
    # базового контура). None — по умолчанию: у зон с обучаемыми связями
    # внутри (смысловая кора).
    inhibition_adapts: bool | None = None
    # Врождённые колонки: E-клетки по columns штук связаны каждая с каждой
    # весом column_weight (аттрактор). 0 — нет колонок.
    columns: int = 0
    column_weight: float = 0.0
    # Потолок медленного (NMDA) тока, мВ: рецепторы насыщаются. None — нет.
    slow_max: float | None = None
    # Доля быстрого тока у зоны памяти; None — общая memory_ampa_ratio.
    ampa_ratio: float | None = None


@dataclass
class PathwaySpec:
    """
    Проводящий путь между зонами: E-нейроны src -> E и I нейроны dst.

    plastic=True — путь учится (STDP + dopamine).
    plastic=False — врождённая «проводка».
    """

    src: str
    dst: str
    k: int
    weight: tuple[float, float]
    plastic: bool = False
    cap: float = 2.0
    # Сколько входов от src получает каждый I-нейрон dst
    # (feedforward inhibition: сильный вход сразу будит торможение).
    # [замер] без него зоны срывались в синхронные залпы.
    k_inhibitory: int = 50
    inhibitory_weight: float = 1.5
    # Участвует ли выученное по пути в ожидании следующего слова.
    # False — путь модулирующий: учится и подаёт ток, но в предсказание
    # не входит (его читают отдельно, как «чувство -> слова о нём»).
    predictive: bool = True




def default_areas() -> list[AreaSpec]:
    # Доли зон: смысловой памяти — больше всех (места слов = ёмкость).
    # [замер] 20 тыс., seed 42 / 7: смысл 0.5 / слух 0.2 / память 0.2 / рот
    # 0.1 — мест 1852, факты 24 → 23, 24 → 25; смысл 0.7 / 0.1 / 0.1 /
    # 0.05 — мест 2718 (×1.47), факты 23 → 23, 25 → 25; узнавание форм
    # чуть грубее («францию» → «франции» первым, вторым «германия»).
    return [
        AreaSpec(
            "auditory", "слуховая кора / зона Вернике (формы слов)",
            0.10, k_ee=30, ee_plastic=False, target_activity=0.05,
        ),
        AreaSpec(
            # [не подбиралось] 100 входов E->E: основная память, ей нужно
            # больше всего синапсов. 0.66: 0.04 отдано цели (было 0.70).
            "association", "ассоциативная кора (смысловая память)",
            0.66, k_ee=100,
        ),
        AreaSpec(
            # Рабочая память держит больше активных клеток (8%): в ней
            # одновременно звучат несколько последних слов.
            "prefrontal", "префронтальная кора (рабочая память)",
            0.10, kind="memory", k_ee=20, ee_plastic=False,
            ee_weight=(0.05, 0.05), target_activity=0.08,
        ),
        AreaSpec(
            "motor", "моторная речевая зона / зона Брока (рот)",
            0.05, k_ee=30, ee_plastic=False,
        ),
        # Цель (ПФК): держит слова вопроса, пока их не вытеснят новые, —
        # сама сеть, а не след из кода. Врождённые колонки по 4 клетки
        # (как место слова), связанные каждая с каждой на медленном NMDA:
        # разбуженная колонка горит сама (аттрактор, Compte 2000); общее
        # торможение зоны держит ~9 колонок сразу (7±2 — без подбора),
        # дольше всех горевшие гаснут первыми (их торможение выросло).
        # Числа — со стенда, каждое по правилу (DESIGN «Цель в ПФК»):
        #  - column_weight 40: одно услышанное слово (60 мс) зажигает
        #    колонку (6 — гасла, 80 — то же, но 166 Гц);
        #  - ampa_ratio 0.05: держит медленный ток, а не быстрый (при
        #    полном быстром колонка горит 230 Гц и душит соседей);
        #  - slow_max 21 мВ: потолок NMDA на 1 мВ выше порога — колонка
        #    ровно держит себя. Частота всё равно ~83 Гц (в ПФК 20–50) —
        #    добавляет быстрый ток соседей; [не подбиралось] дальше.
        AreaSpec(
            "goal", "ПФК: цель (держит вопрос до ответа)",
            0.04, kind="memory", k_ee=20, ee_plastic=False,
            ee_weight=(0.04, 0.06), target_activity=0.0,
            columns=4, column_weight=40.0, ampa_ratio=0.05, slow_max=21.0,
            inhibition_adapts=True,
        ),
        AreaSpec(
            # Чувства: каждая эмоция возбуждает свой набор нейронов
            # (сигнал изнутри тела). Связи отсюда в смысл учатся — так
            # мозг узнаёт, какими словами говорят о том, что он чувствует.
            # Без гомеостаза (target_activity=0): стрелять должны клетки
            # чувства, а не случайные — иначе к словам привязывается шум.
            "limbic", "лимбическая система (чувства)",
            0.04, k_ee=20, ee_plastic=False, target_activity=0.0,
        ),
        # Ядра нейромедиаторов: маленькие, без путей в кору — действуют
        # химически (доля выстреливших = дофамин / норадреналин). Без
        # гомеостаза: молчат, пока нет сигнала. [не подбиралось] доли 0.5%.
        # VTA не привыкает: дофамин падает, когда улучшается предсказание
        # (это уже в ошибке предсказания), а не от усталости клеток.
        AreaSpec(
            "vta", "дофаминовое ядро (VTA)",
            0.005, k_ee=10, ee_plastic=False, target_activity=0.0,
        ),
        # Голубое пятно привыкает за секунды: после серии неожиданностей
        # стихает, после затишья снова отвечает полностью.
        # [замер] адаптация как у коры (1 мВ, 150 мс) и даже 20 мВ / 150 мс:
        # при чтении нового текста возбуждение 0.98 (99% слов выше 0.65)
        # против 0.26 у прежней формулы привыкания. См. DESIGN.
        # Миндалина: две группы клеток — «хорошо» и «плохо». Учит, какие
        # слова предвещают похвалу или ругань; слыша их снова, мозг
        # предвкушает (огорчается заранее). [не подбиралось] 1%.
        AreaSpec(
            "amygdala", "миндалина (хорошо / плохо)",
            0.01, k_ee=10, ee_plastic=False, target_activity=0.0,
        ),
        # Категории (зона-хаб, височный полюс): клетки по category_cells —
        # одна категория; слово вступает в неё синапсами, она предсказывает
        # продолжения своими. [не подбиралось] 2%.
        AreaSpec(
            "category", "височный полюс (категории)",
            0.02, k_ee=10, ee_plastic=False, target_activity=0.0,
        ),
        AreaSpec(
            "lc", "голубое пятно (норадреналин)",
            0.005, k_ee=10, ee_plastic=False, target_activity=0.0,
            adapt_b=10.0, adapt_tau=5000.0,
        ),
    ]


def default_pathways() -> list[PathwaySpec]:
    return [
        # Восприятие: формы слов -> смысл.
        # [замер] k=100 и вес 4: одно и то же слово даёт ансамбль со
        # сходством 0.58 между повторами против 0.05 у разных слов.
        # k=20 давало 0.07 (смысловая зона отвечала шумом); вес 5-8
        # не лучше, а моторная зона начинала отвечать на всё подряд.
        PathwaySpec("auditory", "association", k=100, weight=(4.0, 4.0)),
        # Смысл -> рабочая память (эхо последних слов).
        # [замер] вес 3 — память молчала на коротких фразах; 10 —
        # 12% активных и шум в ожиданиях; 6 — память различает
        # «открыть файл» / «закрыть файл» (0.43 повтор против 0.32).
        # Торможение 6 = вес возбуждения: иначе синхронные залпы.
        PathwaySpec("association", "prefrontal", k=100, weight=(6.0, 6.0),
                    inhibitory_weight=6.0),
        # Контекст -> ожидание следующего смысла. Учится.
        # [замер] k=20: при k=50-60 ожидания сильнее зашумлены.
        # Вклад в ожидание — context_gain, режим gain (конъюнкция).
        PathwaySpec("prefrontal", "association", k=20, weight=(0.02, 0.10),
                    plastic=True, cap=2.0, k_inhibitory=0),
        # Чувство -> слова о нём. Учится, как и контекст.
        # [замер] predictive=False: чувство держится всю реплику, и его
        # выученный вклад добавлялся к ожиданию после КАЖДОГО слова —
        # «париж» после «столица франции» падал с 1-го места на 8-13-е.
        # Без этого пути в ожидании — снова 1-е (docs/DESIGN.md).
        # [замер] k=30: у клетки чувства ~560 исходящих — она «хаб», и
        # таблица событий (ширина = максимум исходящих) раздувалась для
        # всех нейронов. k=8 — ~150.
        # Цель -> смысл: учится, как контекст; на дендриты (как всё из
        # зон памяти) — цель выбирает среди того, что предлагает слово.
        PathwaySpec("goal", "association", k=20, weight=(0.02, 0.10),
                    plastic=True, cap=2.0, k_inhibitory=0),
        PathwaySpec("limbic", "association", k=8, weight=(0.02, 0.10),
                    plastic=True, cap=2.0, k_inhibitory=0, predictive=False),
        # Смысл -> миндалина: какие слова к добру, какие к худу. Учится не
        # STDP, а на похвалу/ругань (language._learn_value); при рождении
        # пустой.
        PathwaySpec("association", "amygdala", k=50, weight=(0.0, 0.0),
                    k_inhibitory=0, predictive=False),
        # Слово -> категория (членство) и категория -> слово (что она
        # предсказывает). Учатся по совпадению (language._learn_categories),
        # при рождении пустые.
        PathwaySpec("association", "category", k=50, weight=(0.0, 0.0),
                    k_inhibitory=0, predictive=False),
        # [замер] k=50: у клетки категории ~1250 исходящих синапсов, и
        # таблица событий (ширина = максимум исходящих) раздулась для всех
        # нейронов — чтение 60 → 107 с. Клетке смысла нужно лишь несколько
        # входов от категорий (растут по опыту): k=8; после того как смыслу
        # отдали 70% нейронов — k=4 (~150 исходящих у клетки категории).
        PathwaySpec("category", "association", k=4, weight=(0.0, 0.0),
                    k_inhibitory=0, predictive=False),
        # Смысл -> артикуляция (рот).
        # [замер] вес 6: моторный ансамбль слова 0.33-0.45 сходства между
        # повторами (4 -> 0.26). k=300 хуже: 44-83 из 224 слов «рот»
        # узнаёт против 130 из 258 при k=100.
        PathwaySpec("association", "motor", k=100, weight=(6.0, 6.0),
                    inhibitory_weight=6.0),
    ]


