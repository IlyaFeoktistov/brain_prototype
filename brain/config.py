@dataclass
class AreaSpec:
    """
    Зона мозга.

    kind = "cortex"  E (AdEx) + I (быстрый LIF), быстрые синапсы
    kind = "memory"  E с медленным NMDA-подобным током (рабочая память)
    share           доля от общего числа нейронов
    """

    name: str
    title: str
    share: float
    kind: str = "cortex"
    # Локальные связи внутри зоны. [не подбиралось] 50 входов.
    k_ee: int = 50
    ee_plastic: bool = True
    # [биология] врождённые связи слабые и случайные: сильные
    # должны появиться только от опыта.
    ee_weight: tuple[float, float] = (0.05, 0.20)
    ee_cap: float = 3.0
    # Целевая доля E-нейронов, отвечающих на слово.
    # [биология] в коре на стимул отвечают единицы процентов клеток.
    target_activity: float = 0.04
    # Своя адаптация E-нейронов: мВ за спайк и время затухания (мс);
    # None — как у коры.
    adapt_b: float | None = None
    adapt_tau: float | None = None
    # Медленная следовая гиперполяризация (sAHP, Ca²⁺-зависимый K⁺-ток;
    # Madison & Nicoll 1984): мВ за спайк и время затухания (мс), второй
    # ток рядом с быстрой адаптацией. 0 — нет.
    slow_ahp_b: float = 0.0
    slow_ahp_tau: float = 1500.0
    # Торможение к клетке растёт с её спайками (пластичность торможения
    # базового контура). None — по умолчанию: у зон с обучаемыми связями
    # внутри (смысловая кора).
    inhibition_adapts: bool | None = None
    # Врождённые колонки: E-клетки по columns штук связаны каждая с каждой
    # весом column_weight (аттрактор). 0 — нет колонок.
    columns: int = 0
    column_weight: float = 0.0
    # Потолок медленного (NMDA) тока, мВ: рецепторы насыщаются. None — нет.
    slow_max: float | None = None
    # Доля быстрого тока у зоны памяти; None — общая memory_ampa_ratio.
    ampa_ratio: float | None = None
    # Кто учит связи внутри зоны: "dopamine" или "acetylcholine" (запись
    # с одного раза, гиппокамп) — см. PathwaySpec.modulator.
    ee_modulator: str = "dopamine"
    # Сила фонового шума у E-клеток зоны; None — по типу зоны
    # (background_weight / memory_background_weight).
    background: float | None = None
    # Сила торможения к E-клеткам зоны (множитель ie_weight): у CA3
    # корзинчатые клетки держат вспышку разреженной.
    inhibition: float = 1.0
    # Сила входа E → I зоны (множитель ei_weight): обратное торможение
    # растёт с активностью зоны — вспышка гасит лишнее сама.
    feedback: float = 1.0
    # Скорость гомеостаза возбудимости зоны (множитель homeostasis_rate):
    # у коры — подстройка за слова (так держится разреженный код), в
    # гиппокампе — медленная, как внутренняя пластичность у человека
    # (часы): иначе он то задавливает CA3 в ноль, то держит её у порога.
    homeostasis: float = 1.0
    # Тоническая зона (пейсмейкеры: GPe, GPi): стреляет постоянно — для
    # стенда здоровья это норма, а не очаг.
    tonic: bool = False
    # Передачу по связям внутри зоны подавляет ацетилхолин (CA3).
    ee_ach_suppressed: bool = False
    # STDP связей внутри зоны симметричное: потенциируют оба порядка спайков
    # (пре после поста — тоже LTP). [биология] CA3 → CA3 (Mishra et al. 2016):
    # так клетки, стрелявшие вместе, связываются в обе стороны —
    # автоассоциативная память; несимметричное окно с перевесом депрессии
    # одновременную активность почти не запоминает.
    ee_symmetric: bool = False
    # Гомеостаз возбудимости у каждой клетки своей (intrinsic plasticity,
    # Desai 1999), а не у зоны целиком: часто стреляющая клетка теряет
    # возбудимость, молчащая — набирает. Так конкурентная зона не отдаёт
    # всё одним и тем же победителям, новое занимают новые клетки.
    cell_homeostasis: bool = False
    # Своё окно STDP у клеток зоны (мс): след спайка живёт на клетке, и
    # у разных синапсов окна разные (Bi & Poo 1998 — ~20 мс; Abbott &
    # Nelson 2000). None — общее (BrainConfig.stdp_*: под слова).
    stdp_tau_plus: float | None = None
    stdp_ltp_rise: float | None = None
    stdp_tau_minus: float | None = None
    # Масштабирование связей внутри зоны по сумме (synaptic_scaling).
    # False — у рта по буквам: врождённые колонки артикуляций сильнее бюджета.
    ee_scaled: bool = True
    # Сколько плато дендрита поднимает сому, мВ (None — общее dendrite_soma_mv).
    # У плана рта плато слова держит его буквы (BAC firing, Larkum 1999).
    dendrite_soma_mv: float | None = None
    # Затухание тока ветки, мс (None — общее dendrite_tau_ms, 100).
    dendrite_tau_ms: float | None = None
    # Пул торможения зоны (корзинчатые клетки, k-WTA): каждый спайк E-клетки
    # зоны на ~pool_inhibition_tau_ms тормозит все её E-клетки на столько мВ —
    # побеждают немногие самые возбуждённые, зона не глохнет целиком. 0 — нет.
    pool_mv: float = 0.0



@dataclass
class SensorSpec:
    """
    Орган-датчик (разъём тела): свой участок рецепторов и зона коры, куда
    он входит. Мозг знает только свои клетки; что рецепторы чувствуют —
    дело органа (улитка, сетчатка), откуда сигнал — дело мира.

    wiring = "random"   клетка зоны берёт k случайных рецепторов (ухо)
    wiring = "oriented" сетчатка → V1: простая клетка собирает входы,
                        выстроенные в линию (см. engine._wire_oriented)
    """

    name: str
    area: str
    size: int
    k: int
    weight: float
    inhibitory_gain: float = 1.0
    # Сетка рецепторов (сетчатка): строки × столбцы одного слоя, слоёв
    # ON и OFF два. 0 — без геометрии.
    rows: int = 0
    cols: int = 0
    wiring: str = "random"

@dataclass
class PathwaySpec:
    """
    Проводящий путь между зонами: E-нейроны src -> E и I нейроны dst.

    plastic=True — путь учится (STDP + dopamine).
    plastic=False — врождённая «проводка».
    """

    src: str
    dst: str
    k: int
    weight: tuple[float, float]
    plastic: bool = False
    cap: float = 2.0
    # Сколько входов от src получает каждый I-нейрон dst
    # (feedforward inhibition: сильный вход сразу будит торможение).
    # [замер] без него зоны срывались в синхронные залпы.
    k_inhibitory: int = 50
    inhibitory_weight: float = 1.5
    # Участвует ли выученное по пути в ожидании следующего слова.
    # False — путь модулирующий: учится и подаёт ток, но в предсказание
    # не входит (его читают отдельно, как «чувство -> слова о нём»).
    predictive: bool = True
    # Кто превращает след STDP в вес: "dopamine" — ошибка предсказания;
    # "acetylcholine" — бодрствование: запись с одного раза (гиппокамп);
    # "coincidence" — никто: путь из зоны, стреляющей непрерывно (ПФК,
    # цель), учится только совпадением под дофамином (language._learn_context),
    # и во сне его метку ставит то же совпадение (DESIGN «Общее слово
    # богатело во сне»).
    modulator: str = "dopamine"
    # Передачу по пути подавляет ацетилхолин (выход гиппокампа при записи).
    ach_suppressed: bool = False
    # Топографический путь: зоны — карты (клетки сеткой, как места слов в
    # Concepts), получатель собирает k входов с круга на карте источника
    # вокруг своей проекции; площадь круга — topographic × k клеток. 0 —
    # входы со всей зоны случайно.
    topographic: float = 0.0
    # Масштабирование синапсов по сумме входа (synaptic_scaling). False —
    # путь-словарь: у клетки сотни выученных входов, но горит один за раз,
    # и клетка стреляет нормально — масштабирование по частоте (Turrigiano)
    # её бы не трогало; бюджет по сумме весов — упрощение (долг).
    scaled: bool = True
    # Блок в блок: клетка получателя берёт все blocks клеток блока с тем же
    # номером у источника (колонки артикуляций плана → выбора). 0 — нет.
    blocks: int = 0
    # Ступень зрительного пути: окно поля (px), с которого клетка берёт
    # входы (engine._retinotopic_pre). 0 — нет.
    retinotopic: float = 0.0
    # Боковое торможение, учащееся по Vogels et al. 2011 (engine.
    # inhibitory_plasticity): вес отрицательный (торможение через местные
    # тормозные клетки — упрощение: связь E → E со знаком минус), сила
    # растёт, когда сосед активен, а клетка стреляет выше нормы
    # (inhibitory_target_hz), и падает, когда ниже. Потолок — cap.
    vogels: bool = False
    # Масштабирование в обе стороны (Turrigiano et al. 1998: при малом входе
    # синапсы клетки растут, при большом — уменьшаются): суммарный вес
    # клетки по пути держится у бюджета. False — только урезание сверху.
    scale_up: bool = False
    # Сложные клетки V1: с retinotopic — окно квадрата (px), входы — простые
    # клетки той же ориентации (engine._complex_pre).
    complex_cells: bool = False
    # Сдвиг блоков: блок b получателя — от блока b − shift источника.
    shift: int = 0
    # Своё имя пути (по умолчанию «src -> dst») — когда между зонами два пути
    # или путь внутри зоны.
    name: str = ""
    # На дендриты получателя, даже если источник — не зона памяти (часы →
    # рот: момент слова — половина конъюнкции «слово ∧ момент» на ветке).
    dendrite: bool = False




